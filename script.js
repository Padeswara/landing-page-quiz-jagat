let current = 0;
let score = 0;
let answered = false;
let drag = null;
const music = new Audio('audio/music-gameplay.mp3');
const tapSound = new Audio('audio/tap.mp3');
const swipeSound = new Audio('audio/swipe.mp3');
music.loop = true;
music.volume = 0.35;
music.preload = 'metadata';
tapSound.preload = 'auto';
swipeSound.preload = 'auto';
let soundMuted = false;
let musicStarted = false;
let instructionTimer = null;

function playAudio(audio, restart = false) {
  try {
    if (restart) audio.currentTime = 0;
    audio.play().catch(() => {});
  } catch {
    // Audio availability must not interrupt the quiz.
  }
}

function playEffect(audio) {
  if (!soundMuted) playAudio(audio, true);
}

function startMusic() {
  musicStarted = true;
  if (music.paused) playAudio(music);
}

$('#sound-toggle').addEventListener('click', () => {
  soundMuted = !soundMuted;
  [music, tapSound, swipeSound].forEach((audio) => { audio.muted = soundMuted; });
  $('#sound-toggle img').src = soundMuted ? 'img/muted.svg' : 'img/unmute.svg';
  $('#sound-toggle').setAttribute('aria-label', soundMuted ? 'Aktifkan suara' : 'Matikan suara');
  $('#sound-toggle').setAttribute('aria-pressed', String(soundMuted));
  if (!soundMuted && musicStarted) startMusic();
});

function showScreen(id) {
  window.clearTimeout(instructionTimer);
  instructionTimer = null;
  $('#game-share-status').textContent = '';
  $('#question-progress').hidden = id !== 'play';
  $('#sound-toggle').hidden = id !== 'play';
  document.querySelectorAll('.screen').forEach((screen) => {
    screen.hidden = screen.id !== id;
  });
  if (id === 'play') {
    startMusic();
  } else {
    music.pause();
    music.currentTime = 0;
    musicStarted = false;
  }
}

function resetCard() {
  drag = null;
  card.classList.remove('dragging');
  card.style.transform = '';
  card.style.opacity = '';
}

async function swipeCard(choice) {
  const startTransform = getComputedStyle(card).transform;
  const pointerId = drag?.id;
  const source = drag?.source;
  drag = null;
  card.classList.remove('dragging');
  if (pointerId !== undefined && source.hasPointerCapture(pointerId)) {
    source.releasePointerCapture(pointerId);
  }

  const direction = choice === 'fact' ? -1 : 1;
  const distance = $('.game').clientWidth + card.clientHeight;
  const endTransform = `translateX(${direction * distance}px) rotate(${direction * 25}deg)`;
  card.style.transform = endTransform;
  card.style.opacity = '0';

  const animation = card.animate(
    [
      { transform: startTransform, opacity: 1 },
      { transform: endTransform, opacity: 0 },
    ],
    {
      duration: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 0 : 350,
      easing: 'cubic-bezier(0.4, 0, 1, 1)',
    }
  );
  await animation.finished;
}

const questionProgress = $('#question-progress');
questionProgress.setAttribute('aria-valuemax', questions.length);
const progressSegments = questions.map(() => {
  const segment = document.createElement('span');
  segment.setAttribute('aria-hidden', 'true');
  questionProgress.append(segment);
  return segment;
});

function updateQuestionProgress(completed) {
  progressSegments.forEach((segment, index) => {
    segment.classList.toggle('is-answered', index < completed);
  });
  questionProgress.setAttribute('aria-valuenow', completed);
  questionProgress.setAttribute('aria-valuetext', `${completed} dari ${questions.length} soal terjawab`);
}

function renderQuestion() {
  answered = false;
  updateQuestionProgress(current);
  resetCard();
  [card, $('#next-question-card'), $('.card-under-middle')]
    .forEach((layer, offset) => {
      layer.style.setProperty('--card-pose', cardPoses[offset]);
    });
  $('#question-text').textContent = questions[current].text;
  const nextQuestion = questions[current + 1];
  $('#next-question-card').hidden = !nextQuestion;
  $('#next-question-text').textContent = nextQuestion ? nextQuestion.text : '';
  $('.card-under-middle').hidden = current + 2 >= questions.length;
  $('#opinion').disabled = false;
  $('#fact').disabled = false;
  card.focus({ preventScroll: true });
}

async function showInstructions() {
  const startButton = $('#start');
  if (startButton.disabled) return;
  playEffect(tapSound);
  startButton.disabled = true;
  await $('#instruction img').decode().catch(() => {});
  showScreen('instruction');
  $('#instruction').focus({ preventScroll: true });
  startButton.disabled = false;
  instructionTimer = window.setTimeout(() => {
    if (!$('#instruction').hidden) startGame(false);
  }, 3000);
}

function startGame(withTapSound = true) {
  if (withTapSound) playEffect(tapSound);
  $('#share-status').textContent = '';
  current = 0;
  score = 0;
  showScreen('play');
  renderQuestion();
}

async function answer(choice) {
  if (answered || $('#play').hidden) return;
  answered = true;
  playEffect(swipeSound);
  updateQuestionProgress(current + 1);
  const question = questions[current];
  const correct = choice === question.answer;
  if (correct) score += 1;
  $('#opinion').disabled = true;
  $('#fact').disabled = true;
  $('#feedback-title').textContent = correct
    ? `Benar! Itu adalah ${question.answer === 'fact' ? 'fakta' : 'opini'}.`
    : `Salah! Jawaban yang benar adalah ${question.answer === 'fact' ? 'fakta' : 'opini'}.`;
  dialog.classList.add('feedback-artwork');
  dialog.classList.toggle('feedback-correct', correct);
  dialog.classList.toggle('feedback-incorrect-fact', !correct && question.answer === 'fact');
  $('#feedback-text').hidden = true;
  const feedbackImage = $('#feedback-image');
  feedbackImage.hidden = false;
  const answerType = question.answer === 'fact' ? 'fakta' : 'opini';
  feedbackImage.src = correct
    ? `img/popup-benar-${answerType}.png`
    : `img/popup-salah-jawaban-${answerType}.png`;
  $('#feedback-icon').textContent = correct ? '✓' : '×';
  $('#feedback-icon').classList.toggle('incorrect', !correct);
  $('#feedback-fact-top').hidden = correct || question.answer !== 'fact';
  const explanation = $('#feedback-description');
  explanation.hidden = correct || question.answer === 'opinion';
  explanation.textContent = explanation.hidden ? '' : `Kenapa?\n\n${question.explanation}`;
  $('#next').setAttribute('aria-label',
    current === questions.length - 1 ? 'Lihat hasil' : correct ? 'Soal berikutnya' : 'Lanjut');
  const nextImage = $('#next img');
  nextImage.src = correct ? 'img/button-next-question.png' : 'img/button-lanjut.png';
  await Promise.all([
    swipeCard(choice),
    feedbackImage.decode().catch(() => {}),
    nextImage.decode().catch(() => {}),
  ]);
  dialog.showModal();
  $('#next').focus();
}

