const suppressedAnswerClicks = new WeakSet();
[$('#fact'), $('#opinion')].forEach((button) => {
  button.addEventListener('click', (event) => {
    if (event.detail !== 0 && suppressedAnswerClicks.has(button)) {
      suppressedAnswerClicks.delete(button);
      event.preventDefault();
      return;
    }
    answer(button.id);
  });
});
dialog.addEventListener('click', nextQuestion);
dialog.addEventListener('cancel', (event) => event.preventDefault());

card.addEventListener('keydown', (event) => {
  if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
    event.preventDefault();
    answer(event.key === 'ArrowLeft' ? 'fact' : 'opinion');
  }
});

function beginDrag(event) {
  if (answered || drag || $('#play').hidden || !event.isPrimary || event.button !== 0) return;
  const source = event.target.closest('.answer') || event.currentTarget;
  suppressedAnswerClicks.delete(source);
  drag = { x: event.clientX, y: event.clientY, id: event.pointerId, source, moved: false };
  source.setPointerCapture(event.pointerId);
  card.classList.add('dragging');
}

function moveDrag(event) {
  if (!drag || event.pointerId !== drag.id) return;
  const distance = event.clientX - drag.x;
  if (Math.hypot(distance, event.clientY - drag.y) > 10) drag.moved = true;
  card.style.transform = `translateX(${distance}px) rotate(${Math.max(
    -18,
    Math.min(18, distance / 12)
  )}deg) ${card.style.getPropertyValue('--card-pose')}`;
}

function endDrag(event) {
  if (!drag || event.pointerId !== drag.id) return;
  const distance = event.clientX - drag.x;
  const vertical = event.clientY - drag.y;
  if (drag.moved || Math.hypot(distance, vertical) > 10) {
    suppressedAnswerClicks.add(drag.source);
  }
  const threshold = Math.min(75, card.clientWidth * 0.25);
  if (
    Math.abs(distance) >= threshold &&
    Math.abs(distance) > Math.abs(vertical)
  ) {
    answer(distance < 0 ? 'fact' : 'opinion');
  } else {
    resetCard();
  }
}
function cancelDrag(event) {
  if (drag && event.pointerId === drag.id) {
    suppressedAnswerClicks.add(drag.source);
    resetCard();
  }
}

const playScreen = $('#play');
playScreen.addEventListener('pointerdown', beginDrag);
playScreen.addEventListener('pointermove', moveDrag);
playScreen.addEventListener('pointerup', endDrag);
playScreen.addEventListener('pointercancel', cancelDrag);
playScreen.addEventListener('lostpointercapture', cancelDrag);
